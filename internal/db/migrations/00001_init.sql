CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    text        NOT NULL,
    last_name     text        NOT NULL,
    email         text        UNIQUE,
    phone         text,
    city          text        NOT NULL,
    language      text        NOT NULL CHECK (language IN ('tr', 'en')),
    sms_consent   boolean     NOT NULL DEFAULT false,
    email_consent boolean     NOT NULL DEFAULT false,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE user_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES users (id),
    type       text        NOT NULL CHECK (type IN ('cart_add', 'purchase')),
    created_at timestamptz NOT NULL
);

-- segment: "most recent cart_add" and "purchase after it" per user
CREATE INDEX user_events_user_type_time_idx ON user_events (user_id, type, created_at);

CREATE TABLE campaigns (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brief                text        NOT NULL,
    segment_rule         jsonb,
    sms_content          text,
    email_subject        text,
    email_body           text,
    status               text        NOT NULL DEFAULT 'draft'
                         CHECK (status IN ('draft', 'ready', 'approved', 'completed')),
    sms_audience_count   integer,
    email_audience_count integer,
    over_limit_policy    text        NOT NULL DEFAULT 'fallback'
                         CHECK (over_limit_policy IN ('fallback', 'skip')),
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    approved_at          timestamptz
);

CREATE TABLE messages (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id         bigint      NOT NULL REFERENCES campaigns (id),
    user_id             bigint      NOT NULL REFERENCES users (id),
    channel             text        NOT NULL CHECK (channel IN ('sms', 'email')),
    to_address          text        NOT NULL,
    subject             text,
    body                text        NOT NULL,
    status              text        NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'sending', 'sent', 'retry_scheduled', 'failed', 'skipped')),
    attempts            integer     NOT NULL DEFAULT 0,
    -- NOT NULL: a NULL would make "next_attempt_at <= now()" false and the row would never be claimed
    next_attempt_at     timestamptz NOT NULL DEFAULT now(),
    locked_until        timestamptz,
    last_error          text,
    provider_message_id text,
    sent_at             timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, user_id, channel),
    CHECK (channel = 'email' OR subject IS NULL)
);

-- worker claim: partial indexes only contain rows still awaiting work, so they stay small
CREATE INDEX messages_claimable_idx ON messages (next_attempt_at) WHERE status IN ('pending', 'retry_scheduled');
CREATE INDEX messages_lease_idx     ON messages (locked_until)    WHERE status = 'sending';
-- dashboard aggregate (GROUP BY channel, status)
CREATE INDEX messages_campaign_status_idx ON messages (campaign_id, channel, status);

CREATE TABLE llm_calls (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id       bigint      NOT NULL REFERENCES campaigns (id),
    step              text        NOT NULL CHECK (step IN ('audience', 'messages')),
    prompt_version    text        NOT NULL,
    raw_response      text,
    validation_errors jsonb,
    repair_attempt    integer     NOT NULL DEFAULT 0,
    transport_attempt integer     NOT NULL DEFAULT 0,
    input_tokens      integer,
    output_tokens     integer,
    latency_ms        integer,
    created_at        timestamptz NOT NULL DEFAULT now()
);

